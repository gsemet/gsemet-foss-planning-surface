#!/usr/bin/env node
// P10 checklist extractor. Read-only on the repository: it reads sources and writes only under
// p10-requirements/checklists/ and p10-requirements/tools/.cache/.
//
// Re-entrant: item ids are kept in tools/checklist-ids.json, keyed by a natural key; an id is
// never reused and new items take the next free number of their kind. The "SwRS" column of an
// existing checklist file is read back and preserved by id. Items that disappeared from the
// sources stay listed with status "gone" (their id stays retired).
//
// Usage (CR 059): run from a directory with a .nvmrc (the refactor worktree), passing the code root:
//   fnm exec -- node <this folder>/tools/extract-checklists.mjs <code-root>
// <code-root> (default: the repo that holds this folder) is where src/, test/, package.json and
// CHANGELOG.md are read; archives and esbuild always come from the repo that holds this folder.
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const p10 = path.dirname(here);
const home = path.resolve(here, "../../../../..");
const repo = path.resolve(process.argv[2] ?? home);
const out = path.join(p10, "checklists");
const cache = path.join(here, ".cache");
mkdirSync(out, { recursive: true });
mkdirSync(cache, { recursive: true });
const read = (rel) => readFileSync(path.join(repo, rel), "utf8");
const require = createRequire(path.join(home, "package.json"));
const esbuild = require("esbuild");
const scopeMap = JSON.parse(readFileSync(path.join(here, "scope-map.json"), "utf8"));
