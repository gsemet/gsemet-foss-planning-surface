/** Transpiles one self-contained TS module (type-only imports) with the repo's esbuild (in memory) to an ESM file under tools/.cache and imports it. */
async function loadTs(rel) {
  const js = esbuild.buildSync({ entryPoints: [path.join(repo, rel)], bundle: true, write: false, format: "esm", target: "es2022", platform: "node", logLevel: "silent" }).outputFiles[0].text;
  const file = path.join(cache, rel.replace(/[\\/]/g, "__").replace(/\.ts$/, ".mjs"));
  writeFileSync(file, js);
  return import(pathToFileURL(file).href + "?t=" + Date.now());
}

// ---------------------------------------------------------------- id registry and output
const idsFile = path.join(here, "checklist-ids.json");
const ids = existsSync(idsFile) ? JSON.parse(readFileSync(idsFile, "utf8")) : {};
const claimed = new Set();
function idFor(kind, key) {
  const table = (ids[kind] ??= { next: 1, keys: {} });
  if (!table.keys[key] && kind === "CTL") {
    // CR 059: page controls moved between files; keep the id of the same label under its old file.
    const label = key.slice(key.indexOf(":", "control:".length) + 1);
    const old = Object.keys(table.keys).find((k) => k.endsWith(`:${label}`) && !claimed.has(table.keys[k]) && !k.startsWith("control:src/page/") && !k.startsWith("control:src/core/"));
    if (old) { table.keys[key] = table.keys[old]; delete table.keys[old]; }
  }
  if (!table.keys[key]) table.keys[key] = `C-${kind}-${String(table.next++).padStart(3, "0")}`;
  claimed.add(table.keys[key]);
  return table.keys[key];
}
const cell = (v) => String(v ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();

/** Reads the SwRS column back from an existing checklist file. */
function previousSwrs(file) {
  const map = new Map();
  if (!existsSync(file)) return map;
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const m = line.match(/^\| (C-[A-Z]+-\d{3}) \|/);
    if (!m) continue;
    const cols = line.split(/(?<!\\)\|/).map((c) => c.trim());
    map.set(m[1], cols[cols.length - 2]);
  }
  return map;
}

const summary = [];
/**
 * items: [{ key, scope, item, details, source }]. Writes checklists/<name>.md with columns
 * ID | Scope | Item | Details | Source | SwRS.
 */
function writeChecklist(name, kind, title, intro, items) {
  const file = path.join(out, `${name}.md`);
  const swrs = previousSwrs(file);
  const seen = new Set();
  const rows = items.map((it) => {
    const id = idFor(kind, it.key);
    if (seen.has(id)) throw new Error(`duplicate key ${kind}:${it.key}`);
    seen.add(id);
    return { id, ...it };
  });
  // Retired items: ids known for this kind but absent now.
  const gone = Object.entries(ids[kind]?.keys ?? {}).filter(([, id]) => !seen.has(id));
  const perScope = {};
  for (const r of rows) {
    const s = r.scope.replace(/\?$/, "");
    perScope[s] = (perScope[s] ?? 0) + 1;
  }
  const lines = [
    `# ${title}`,
    "",
    `Generated by \`tools/extract-checklists.mjs\` (read-only extraction). ${intro}`,
    "Do not edit the generated columns by hand; fill only the **SwRS** column (comma-separated",
    "SwRS ids, or `n/a: <reason>` agreed in review). Re-running the extractor keeps that column",
    "and the ids. A scope ending in `?` was guessed by keyword and must be confirmed by the",
    "per-scope analyst.",
    "",
    `Items: ${rows.length}. Per scope: ${SCOPES.filter((s) => perScope[s]).map((s) => `${s} ${perScope[s]}`).join(", ")}.`,
    "",
    "| ID | Scope | Item | Details | Source | SwRS |",
    "| --- | --- | --- | --- | --- | --- |",
    ...rows.map((r) => `| ${r.id} | ${cell(r.scope)} | ${cell(r.item)} | ${cell(r.details)} | ${cell(r.source)} | ${cell(swrs.get(r.id) ?? "")} |`),
  ];
  if (gone.length) {
    lines.push("", "## Retired (no longer in the sources; ids never reused)", "");
    for (const [key, id] of gone) lines.push(`- ${id} — ${key}${swrs.get(id) ? ` (SwRS: ${swrs.get(id)})` : ""}`);
  }
  writeFileSync(file, lines.join("\n") + "\n");
  summary.push({ name, kind, count: rows.length, perScope });
}

